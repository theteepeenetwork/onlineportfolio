import { LegalShell } from "../LegalShell";

export const metadata = { title: "Acceptable Use Policy — StoryJar" };

export default function AcceptableUse() {
  return (
    <LegalShell title="Acceptable Use Policy" intro="What may and may not be put into StoryJar. Teachers are the moderators, so this is mainly a guide for staff.">
      <h2>StoryJar is for children's learning moments</h2>
      <p>It is a place for a child&apos;s own work — drawings, photos of what they&apos;ve made or done, and their words — kept for the class journal. It is not a general photo store or a place for personal or sensitive records. Where a school has switched them on, families and staff can also exchange short messages about a child, inside the school&apos;s office hours; the rules for those are below.</p>

      <h2>The teacher&apos;s role</h2>
      <p>Every moment passes through a teacher before it is kept. Teachers should approve only content that is appropriate, and send back or delete anything that is not. Please do not approve:</p>
      <ul>
        <li>Images or text that identify a child beyond their first name (e.g. surnames, addresses, dates of birth) or that show another child without the school&apos;s consent arrangements being met.</li>
        <li>Anything upsetting, unsafe, discriminatory, or unlawful.</li>
        <li>Personal or special-category information that isn&apos;t needed for the journal (e.g. medical or family details).</li>
        <li>Content that isn&apos;t the child&apos;s own learning work.</li>
      </ul>

      <h2>Not allowed</h2>
      <ul>
        <li>Giving a child their own login, email or password (they don&apos;t need one).</li>
        <li>Sharing login details or letting unauthorised adults access children&apos;s work.</li>
        <li>Using StoryJar to contact children directly or outside the school&apos;s supervision.</li>
        <li>Attempting to access another class&apos;s or family&apos;s data, or to circumvent access controls.</li>
        <li>Uploading malware, or content that infringes others&apos; rights.</li>
      </ul>

      <h2>Messages between families and staff</h2>
      <p>A school may switch on messages between a child&apos;s family and their class teacher. They are delivered only inside the office hours the school sets, in both directions, and they are about one child. For everyone using them:</p>
      <ul>
        <li><strong>Not for emergencies.</strong> If a child is unwell, absent, or the school is needed now, phone the school office. Messages are not read outside school hours.</li>
        <li><strong>About the child&apos;s learning and day.</strong> Please do not put medical details, information about other children or other families, or anything you would not want kept with the child&apos;s school record into a message.</li>
        <li><strong>Courteous.</strong> Staff and families are entitled to the same respect in writing as in the playground. The school may close a conversation, and a teacher may hand a family&apos;s conversation to a colleague.</li>
        <li><strong>Text only, and never to a child.</strong> There are no attachments, links are not clickable, and no child can see or send a message.</li>
        <li><strong>Who can read it is always shown.</strong> A family sees the names of the staff who can see the conversation; the school sees who is in a conversation and whether anyone is waiting for a reply, but never the messages themselves.</li>
      </ul>

      <h2>If something&apos;s wrong</h2>
      <p>If inappropriate content is uploaded, a teacher should return or delete it and, if it raises a safeguarding concern, follow the school&apos;s procedures and inform the <strong>Designated Safeguarding Lead</strong>. See the <a href="/legal/safeguarding">Safeguarding</a> page. We may suspend access where needed to protect children.</p>
    </LegalShell>
  );
}
